"""Run the sample questions through the assistant and write sample_qa.md."""
from assistant import Assistant

QUESTIONS = [
    "What is the expense ratio of Parag Parikh Flexi Cap Fund?",
    "What is the exit load of the Flexi Cap Fund?",
    "What is the minimum SIP for Parag Parikh Large Cap Fund?",
    "What is the lock-in period of the ELSS Tax Saver Fund?",
    "What is the riskometer rating and benchmark of the Large Cap Fund?",
    "How do I download my capital gains statement?",
    "Should I buy Parag Parikh Flexi Cap Fund now?",
    "What were the 5-year returns of the ELSS fund?",
    "My PAN is ABCDE1234F, can you check my folio?",
    "What is the expense ratio?",
]

bot = Assistant()
out = ["# Sample Q&A", "",
       "Generated by running `python make_samples.py` against the assistant. "
       "Types: answer = factual reply, refusal = advice question declined, performance = returns question "
       "redirected to the factsheet, pii = personal details blocked, clarify = scheme not named.", ""]
for i, q in enumerate(QUESTIONS, 1):
    a = bot.ask(q)
    out += [f"**{i}. {q}**", "", f"> {a.text}", ">", f"> Source: {a.url}"]
    if a.updated:
        out += [">", f"> Last updated from sources: {a.updated}"]
    out += ["", f"_Type: {a.kind}_", ""]
open("sample_qa.md", "w").write("\n".join(out))
print("\n".join(out))
